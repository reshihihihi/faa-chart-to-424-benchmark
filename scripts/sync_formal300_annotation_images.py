from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from PIL import Image

from materialize_external_pilot_set import collect_checksums, sha256_file, write_json, write_jsonl, write_text


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_FORMAL300 = ROOT / "benchmark_exports" / "derived" / "v2" / "formal300"
DEFAULT_ANNOTATION_ROOT = Path("E:/shujuji/datasets/formal300")


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def image_dimensions(path: Path) -> dict[str, int]:
    with Image.open(path) as image:
        width, height = image.size
    return {"width": width, "height": height}


def file_sha_map(root: Path, suffix: str) -> dict[str, str]:
    return {
        path.name: sha256_file(path)
        for path in sorted(root.glob(f"*{suffix}"))
        if path.is_file()
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Align formal300 image artifacts to the annotation-platform dataset images."
    )
    parser.add_argument("--formal300-dir", type=Path, default=DEFAULT_FORMAL300)
    parser.add_argument("--annotation-root", type=Path, default=DEFAULT_ANNOTATION_ROOT)
    parser.add_argument("--no-copy", action="store_true")
    args = parser.parse_args()

    formal_dir = args.formal300_dir
    annotation_root = args.annotation_root
    formal_manifest = formal_dir / "sample_manifest.jsonl"
    annotation_manifest = annotation_root / "manifest.json"
    formal_rows = read_jsonl(formal_manifest)
    annotation_rows = json.loads(annotation_manifest.read_text(encoding="utf-8"))

    formal_by_chart = {row["chart_id"]: row for row in formal_rows}
    annotation_by_chart = {row["chart_id"]: row for row in annotation_rows}
    missing = sorted(set(formal_by_chart) - set(annotation_by_chart))
    extra = sorted(set(annotation_by_chart) - set(formal_by_chart))
    if missing or extra:
        raise RuntimeError(f"Annotation/formal300 chart_id mismatch. missing={missing[:5]} extra={extra[:5]}")

    before = file_sha_map(formal_dir / "images", ".png")
    source = file_sha_map(annotation_root / "images", ".png")
    if set(before) != set(source):
        raise RuntimeError("Formal300 and annotation image file sets differ.")

    copied = []
    already_same = []
    for row in formal_rows:
        image_name = row["image_file"]
        src = annotation_root / "images" / image_name
        dst = formal_dir / "images" / image_name
        if sha256_file(src) == sha256_file(dst):
            already_same.append(image_name)
        else:
            if not args.no_copy:
                shutil.copy2(src, dst)
            copied.append(image_name)
        row["image_dimensions"] = image_dimensions(dst if not args.no_copy else src)
        row["image_sha256"] = sha256_file(dst if not args.no_copy else src)
        row["annotation_image_source"] = str(src.resolve())
        row["annotation_image_source_sha256"] = sha256_file(src)

    if not args.no_copy:
        write_jsonl(formal_manifest, formal_rows)
        write_json(formal_dir / "manifest.json", formal_rows)
        checksums = collect_checksums(formal_dir)
        write_text(formal_dir / "checksums.sha256", "\n".join(f"{row['sha256']}  {row['path']}" for row in checksums))

    after = file_sha_map(formal_dir / "images", ".png")
    same_after = sum(1 for name, digest in source.items() if after.get(name) == digest)
    report = {
        "status": "formal300_images_aligned_to_annotation_dataset" if same_after == len(source) else "alignment_incomplete",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "formal300_dir": str(formal_dir.resolve()),
        "annotation_root": str(annotation_root.resolve()),
        "annotation_manifest_sha256": sha256_file(annotation_manifest),
        "formal_manifest_sha256": sha256_file(formal_manifest),
        "image_count": len(source),
        "same_before": len(already_same),
        "copied_or_would_copy": len(copied),
        "same_after": same_after,
        "copied_examples": copied[:20],
        "target_policy": "Targets are not copied from annotation_root; formal300 targets remain generated by the current CIFP-to-canonical projection pipeline.",
        "annotation_target_note": "Annotation dataset targets are schema-valid but differ from current projection in status choices for many samples, so they are recorded as a comparison source rather than the frozen scorer target.",
    }
    reports_dir = formal_dir / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    write_json(reports_dir / "annotation_image_alignment_report.json", report)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0 if report["status"] == "formal300_images_aligned_to_annotation_dataset" else 2


if __name__ == "__main__":
    raise SystemExit(main())
